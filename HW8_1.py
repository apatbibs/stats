import numpy as np
import matplotlib.pyplot as plt
from scipy.stats import chi2
np.set_printoptions(suppress=True)

n = 40
t = np.arange(n)


# 1 ====================================================
# alpha_5 = 0
rng = np.random.default_rng(42)
num_simulations = 100000
eps_5 = rng.normal(loc=0.0, scale=1.0, size=(num_simulations, n)) #mu = 0, sigma = 1
y_t1 = eps_5


a5_sim = (2/n) * (y_t1 @ np.cos(2*np.pi*5*t/n))
b5_sim = (2/n) * (y_t1 @ np.sin(2*np.pi*5*t/n))
I_f5 = (n/2) * (a5_sim**2 + b5_sim**2)

fig, ax = plt.subplots(figsize=(10, 6))

ax.hist(I_f5, bins=100, density=True, alpha=0.6, color='forestgreen', label='Simulated $I(f_5)$', edgecolor='white')



# 2 ====================================================
