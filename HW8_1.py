def If5(series):
    n_len = len(series)
    t_idx = np.arange(n_len)
    a_5 = (2/n_len) * np.sum(series*np.cos(2*np.pi*5*t_idx/n_len))
    b_5 = (2/n_len) * np.sum(series*np.sin(2*np.pi*5*t_idx/n_len))
    return (n_len/2) * (a_5**2 + b_5**2)


